export type TranslationKey = keyof typeof translations.cs;

// Czech typography: a line must not end with a one-letter preposition or
// conjunction (a, i, k, o, s, u, v, z) — bind it to the next word with NBSP.
// Two-letter prepositions and "ať/až" get the same treatment (a dangling "ať"
// reads just as badly). Pronouns/verbs (se, si, to, je) are left alone: gluing
// them created odd short lines more often than it helped.
const CS_SHORT_WORD =
  /(^|[\s(„"])([aikosuvzAIKOSUVZ]|[Aa][ťž]|[Nn]a|[Dd]o|[Oo]d|[Pp]o|[Zz]a|[Kk]e|[Vv]e|[Zz]e|[Kk]u) (?=\S)/g;
export const czTypo = (text: string) => text.replace(CS_SHORT_WORD, "$1$2\u00a0");

// Widow protection (both languages): glue the last two words of any longer
// string so a paragraph never ends with a single short word on its own line.
export const noWidow = (text: string) => {
  if (text.length < 40) return text;
  const i = text.lastIndexOf(" ");
  if (i < 0 || text.length - i > 9) return text; // only short last words look orphaned
  return text.slice(0, i) + "\u00a0" + text.slice(i + 1);
};

// Numbers never break: "25 000" stays one token, and a figure stays with its unit
// ("25 000 Kč", "30 %", "52 m²", "1,3 mil."). Czech writes a space before % and
// the units; Vietnamese writes 30% closed up, so only the unit words get glued there.
const THOUSANDS = /(\d) (?=\d{3}(?!\d))/g;
const UNIT_CS = /(\d) (Kč|%|m²|tis\.|mil\.)/g;
const UNIT_VI = /(\d) (Kč|m²|tr\.|triệu)/g;
export const bindNumbers = (text: string, lang: "cs" | "vi") =>
  text.replace(THOUSANDS, "$1\u00a0").replace(lang === "cs" ? UNIT_CS : UNIT_VI, "$1\u00a0$2");

export const t = (lang: "cs" | "vi", key: TranslationKey) => {
  const value = translations[lang][key as keyof typeof translations.cs];
  if (typeof value !== "string") return value;
  return noWidow(bindNumbers(lang === "cs" ? czTypo(value) : value, lang));
};

export default translations;
